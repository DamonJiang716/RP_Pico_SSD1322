inline constexpr Glyph space_glyph = {
    0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00
};


inline constexpr const Glyph* find_glyph(char character)
{
    if (character >= '0' && character <= '9')
    {
        return &digit_glyphs[
            static_cast<std::size_t>(character - '0')];
    }

    if (character >= 'A' && character <= 'Z')
    {
        return &uppercase_glyphs[
            static_cast<std::size_t>(character - 'A')];
    }

    if (character >= 'a' && character <= 'z')
    {
        return &lowercase_glyphs[
            static_cast<std::size_t>(character - 'a')];
    }

    if (character == ' ')
    {
        return &space_glyph;
    }

    return nullptr;
}


inline constexpr bool is_supported(char character)
{
    return find_glyph(character) != nullptr;
}
